# 📘 Q1. WAPP to Sum All the Items in a List
numbers = [10, 20, 30, 40, 50]
total = 0
for i in numbers:
    total = total + i
print("Sum = ", total)   

'''
Output
Sum = 150
Explanation
Create a variable total = 0.
Traverse each element in the list.
Add each element to total.
Print the final sum.
'''